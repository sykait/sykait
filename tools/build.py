def entries():
    for item in LAYOUT:
        if item[0] == "row":
            for fn, fnc, link, alt in item[1]:
                yield fn, fnc
        elif item[2]:
            yield item[1], item[2]


def img_tag(fn, link, alt, width, prefix="assets/", bust=""):
    attr = f'height="{width}"' if width.isdigit() else f'width="{width}"'
    tag = f'<img src="{prefix}{fn}{bust}" {attr} alt="{alt}"/>'
    return f'<a href="{link}">{tag}</a>' if link else tag


def readme():
    rows = ['<!-- Generated by tools/build.py. Edit the panels there, not here. -->', '<div align="center">', ""]
    for item in LAYOUT:
        if item[0] == "row":
            rows.append(" ".join(img_tag(fn, link, alt, item[2]) for fn, _, link, alt in item[1]))
        else:
            _, fn, _, link, alt, width = item
            rows.append(img_tag(fn, link, alt, width))
        rows.append("")
    rows += ["</div>", ""]
    return "\n".join(rows)


BUST = f"?v={int(__import__('time').time())}"  # the local preview always loads the newest panels


